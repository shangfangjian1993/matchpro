def _fold(name: str) -> str:
    """折叠:去重音/去首尾空白/连续空白压缩,便于映射查找"""
    name = unicodedata.normalize("NFKD", name.strip())
    name = "".join(c for c in name if not unicodedata.combining(c))
    return " ".join(name.split())


def normalize(name: str, unmatched: list | None = None) -> str:
    """队名归一化:命中映射返回规范名;未命中返回原样(并记录)"""
    raw = (name or "").strip()
    if not raw:
        return raw
    # loop mapping (max 5): handle chains like Man City -> Manchester City -> Manchester City FC
    # visited 防环:映射表若出现双向/环,立即终止(保证幂等)
    visited = set()
    hit = False
    for _ in range(5):
        folded = _fold(raw)
        mapped = NORMALIZE_MAP.get(raw) or NORMALIZE_MAP.get(folded)
        if not mapped or mapped == raw or mapped in visited:
            break
        visited.add(raw)
        raw = mapped
        hit = True
    # 仅在"确实未命中任何映射"时记录 unmatched(修复:原逻辑把成功映射的队名误记为未匹配)
    if unmatched is not None and not hit:
        unmatched.append((name or "").strip())
    return raw


